// Build a single self-contained, offline, fast index.html from the original.
// Replaces Tailwind Play CDN (runtime compiler) with static CSS, inlines fonts/icons/audio.
const fs = require('fs');
const b64 = p => fs.readFileSync(p).toString('base64');
const txt = p => fs.readFileSync(p, 'utf8').replace(/^﻿/, ''); // strip BOM

let html = fs.readFileSync('src/index-original.html', 'utf8');

// --- 1. Tajawal font @font-face (5 weights, Arabic subset), inlined base64 ---
const weights = [400, 500, 700, 800, 900];
const tajawal = weights.map(w =>
  `@font-face{font-family:'Tajawal';font-style:normal;font-weight:${w};font-display:swap;` +
  `src:url(data:font/woff2;base64,${b64('assets/font/tajawal-' + w + '.woff2')}) format('woff2');}`
).join('');

// --- 2. Font Awesome: core CSS + solid @font-face with inlined woff2 ---
const faCore = txt('assets/fa-core.css');
let faSolid = txt('assets/fa-solid.css');
faSolid = faSolid.replace(
  /src:url\([^)]*\) format\("woff2"\),url\([^)]*\) format\("truetype"\)/,
  `src:url(data:font/woff2;base64,${b64('assets/fa-solid-900.woff2')}) format("woff2")`
);
const faStyle = `<style>${faCore}\n${faSolid}</style>`;

// --- 3. Static Tailwind CSS (generated by CLI, replaces runtime compiler) ---
const twStyle = `<style>${txt('build/tw.css')}</style>`;
const fontStyle = `<style>${tajawal}</style>`;

// --- 4. Swap the 3 external head resources for the inlined equivalents ---
const repl = [
  ['    <script src="https://cdn.tailwindcss.com"></script>', '    ' + twStyle],
  ['    <link rel="stylesheet" href="https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.4.0/css/all.min.css">', '    ' + faStyle],
  ['    <link href="https://fonts.googleapis.com/css2?family=Tajawal:wght@400;500;700;800;900&display=swap" rel="stylesheet">', '    ' + fontStyle],
];
for (const [from, to] of repl) {
  if (!html.includes(from)) throw new Error('MISSING anchor: ' + from.slice(0, 60));
  html = html.replace(from, to);
}

// --- 5. Inline audio as data URIs, stop eager preload ---
for (const n of [7, 8]) {
  const from = `<audio id="sfx-round${n}" src="audio/round${n}.m4a" preload="auto"></audio>`;
  if (!html.includes(from)) throw new Error('MISSING audio anchor ' + n);
  const data = `data:audio/mp4;base64,${b64('src/audio/round' + n + '.m4a')}`;
  html = html.replace(from, `<audio id="sfx-round${n}" src="${data}" preload="none"></audio>`);
}

fs.mkdirSync('dist', { recursive: true });
fs.writeFileSync('dist/index.html', html);
const kb = n => Math.round(n / 1024);
console.log('WROTE dist/index.html  size=' + kb(Buffer.byteLength(html)) + 'KB');
console.log('external refs left: ' + (html.match(/https?:\/\/(cdn|fonts)/g) || []).length);
